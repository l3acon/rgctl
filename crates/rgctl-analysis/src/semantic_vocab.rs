/// Normalize a natural-language semantic query into domain tokens.
///
/// Expands endpoint/controller/… synonyms, filters conversational filler, and
/// rewrites `"end points"`-style phrases before tokenizing.
pub fn normalize_semantic_query_tokens(text: &str) -> HashSet<String> {
    let mut lowered = text.to_ascii_lowercase();
    for phrase in ["end points", "end-points", "end_points", "end point"] {
        if lowered.contains(phrase) {
            lowered = lowered.replace(phrase, "endpoint endpoints");
        }
    }

    let mut raw = HashSet::new();
    rgctl_graph::tokenize_string_into(&lowered, &mut raw);
    for piece in lowered.split(|c: char| !c.is_alphanumeric() && c != '_') {
        if piece.len() >= rgctl_graph::MIN_TOKEN_LEN {
            raw.insert(piece.to_ascii_lowercase());
        }
    }

    let filtered: HashSet<String> = raw
        .iter()
        .filter(|t| !QUERY_FILLER.contains(&t.as_str()))
        .cloned()
        .collect();
    let mut tokens = if filtered.is_empty() { raw } else { filtered };

    expand_domain_synonyms(&mut tokens);
    tokens
}

fn expand_domain_synonyms(tokens: &mut HashSet<String>) {
    let snapshot: Vec<String> = tokens.iter().cloned().collect();
    for t in snapshot {
        match t.as_str() {
            "endpoint" | "endpoints" => {
                tokens.insert("endpoint".into());
                tokens.insert("endpoints".into());
                tokens.insert("route".into());
            }
            "route" | "routes" => {
                tokens.insert("route".into());
                tokens.insert("routes".into());
                tokens.insert("endpoint".into());
            }
            "controller" | "controllers" => {
                tokens.insert("controller".into());
                tokens.insert("controllers".into());
            }
            "service" | "services" => {
                tokens.insert("service".into());
                tokens.insert("services".into());
            }
            "handler" | "handlers" => {
                tokens.insert("handler".into());
                tokens.insert("handlers".into());
            }
            "repository" | "repositories" => {
                tokens.insert("repository".into());
                tokens.insert("repositories".into());
            }
            "provider" | "providers" => {
                tokens.insert("provider".into());
                tokens.insert("providers".into());
            }
            "reflection" | "reflections" | "reflective" | "reflect" => {
                tokens.insert("reflection".into());
                tokens.insert("reflect".into());
                tokens.insert("reflective".into());
            }
            "inject" | "injected" | "injection" | "injections" | "injectable" | "di" => {
                tokens.insert("inject".into());
                tokens.insert("injected".into());
                tokens.insert("injection".into());
                tokens.insert("dependency".into());
            }
            _ => {}
        }
    }
}

/// Collapse synonym groups to one canonical token for `--keyword-and` queries.
pub fn canonicalize_query_keywords(tokens: HashSet<String>) -> Vec<String> {
    const GROUPS: &[&[&str]] = &[
        &["endpoint", "endpoints", "route", "routes"],
        &["controller", "controllers"],
        &["service", "services"],
        &["handler", "handlers"],
        &["repository", "repositories"],
        &["provider", "providers"],
        &["reflection", "reflections", "reflective", "reflect"],
        &[
            "inject",
            "injected",
            "injection",
            "injections",
            "injectable",
            "di",
            "dependency",
        ],
    ];
    let mut out = tokens;
    for group in GROUPS {
        if group.iter().any(|t| out.contains(*t)) {
            for t in *group {
                out.remove(*t);
            }
            out.insert(group[0].to_string());
        }
    }
    let mut list: Vec<String> = out.into_iter().collect();
    list.sort_unstable();
    list
}

/// Parse `assets/vocab_tokens.txt` (one token per line, `#` comments).
pub fn parse_vocab_token_list(text: &str) -> Vec<String> {
    let mut tokens: Vec<String> = text
        .lines()
        .map(str::trim)
        .filter(|line| !line.is_empty() && !line.starts_with('#'))
        .map(str::to_ascii_lowercase)
        .filter(|token| (3..=48).contains(&token.len()))
        .collect();
    tokens.sort_unstable();
    tokens.dedup();
    tokens
}

/// Encode a row-major int8 matrix as an RBVK blob.
pub fn encode_rbvk(tokens: &[String], weights: &[i8], dimensions: usize) -> Result<Vec<u8>> {
    if dimensions == 0 || !dimensions.is_multiple_of(8) {
        return Err(Error::ConfigError(
            "vocab matrix dimensions must be a positive multiple of 8".into(),
        ));
    }
    let expected = tokens
        .len()
        .checked_mul(dimensions)
        .ok_or_else(|| Error::ConfigError("vocab matrix: weights overflow".into()))?;
    if weights.len() != expected {
        return Err(Error::ConfigError(format!(
            "vocab matrix: expected {} weights, got {}",
            expected,
            weights.len()
        )));
    }
    let mut out = Vec::new();
    out.extend_from_slice(MAGIC);
    out.extend_from_slice(&VERSION.to_le_bytes());
    out.extend_from_slice(&(tokens.len() as u32).to_le_bytes());
    out.extend_from_slice(&(dimensions as u32).to_le_bytes());
    for token in tokens {
        let bytes = token.as_bytes();
        let len = u16::try_from(bytes.len())
            .map_err(|_| Error::ConfigError("vocab token longer than u16".into()))?;
        if len == 0 {
            return Err(Error::ConfigError("empty vocab token".into()));
        }
        out.extend_from_slice(&len.to_le_bytes());
        out.extend_from_slice(bytes);
    }
    out.extend(weights.iter().map(|w| *w as u8));
    Ok(out)
}

/// Distill `tokens` through `embedder` into an RBVK blob of `out_dims`.
///
/// Teacher is typically code-daemon. Batches keep ONNX sessions fed without
/// holding a dense `tokens × dims` buffer for the whole vocabulary.
pub fn distill_vocab_matrix(
    embedder: &dyn SemanticEmbedder,
    tokens: &[String],
    out_dims: usize,
    batch_size: usize,
) -> Result<Vec<u8>> {
    if tokens.is_empty() {
        return Err(Error::ConfigError(
            "cannot distill an empty token list".into(),
        ));
    }
    let chunk = batch_size.max(1);
    let mut weights = Vec::with_capacity(tokens.len() * out_dims);
    for batch in tokens.chunks(chunk) {
        let refs: Vec<&str> = batch.iter().map(String::as_str).collect();
        let dense = embedder.embed_batch(&refs)?;
        if dense.len() != batch.len() {
            return Err(Error::ConfigError(format!(
                "embed_batch returned {} rows for {} tokens",
                dense.len(),
                batch.len()
            )));
        }
        for row in dense {
            let resized = resize_dense(&row, out_dims);
            weights.extend(quantize_unit_i8(&resized));
        }
    }
    encode_rbvk(tokens, &weights, out_dims)
}

fn quantize_unit_i8(row: &[f32]) -> Vec<i8> {
    row.iter()
        .map(|value| {
            let scaled = (*value * 127.0).round();
            scaled.clamp(-127.0, 127.0) as i8
        })
        .collect()
}

fn fnv1a(bytes: &[u8]) -> u64 {
    let mut hash: u64 = 0xcbf29ce484222325;
    for byte in bytes {
        hash ^= u64::from(*byte);
        hash = hash.wrapping_mul(0x100000001b3);
    }
    hash
}

fn add_fnv_row(dense: &mut [f32], token: &[u8]) {
    let base = fnv1a(token);
    for (d, slot) in dense.iter_mut().enumerate() {
        let mixed = base
            .wrapping_add((d as u64).wrapping_mul(0x9E3779B97F4A7C15))
            .wrapping_mul(0x100000001b3);
        let centered = (mixed % 251) as i32 - 125;
        *slot += centered as f32;
    }
}

fn l2_normalize(vec: &mut [f32]) {
    let sum_sq: f32 = vec.iter().map(|x| x * x).sum();
    if sum_sq > 0.0 {
        let norm = sum_sq.sqrt();
        for v in vec.iter_mut() {
            *v /= norm;
        }
    }
}

fn resize_dense(native: &[f32], out_dims: usize) -> Vec<f32> {
    if out_dims == native.len() {
        return native.to_vec();
    }
    let mut out = vec![0.0f32; out_dims];
    let copy = native.len().min(out_dims);
    out[..copy].copy_from_slice(&native[..copy]);
    if copy > 0 {
        l2_normalize(&mut out);
    }
    out
}

/// Embedder backed by [`TokenSpaceAccumulator`].
#[derive(Debug, Clone)]
pub struct VocabAccumulateEmbedder {
    dimensions: usize,
}

impl VocabAccumulateEmbedder {
    /// Create an embedder that outputs `dimensions` floats (prefer 256).
    pub fn new(dimensions: usize) -> Result<Self> {
        if dimensions == 0 || dimensions % 8 != 0 {
            return Err(Error::ConfigError(
                "vocab embedder dimensions must be a positive multiple of 8".into(),
            ));
        }
        // Ensure matrix loads at construction time.
        let _ = TokenSpaceAccumulator::global()?;
        Ok(Self { dimensions })
    }
}

impl crate::semantic_embedder::SemanticEmbedder for VocabAccumulateEmbedder {
    fn model_id(&self) -> &str {
        VOCAB_ACCUMULATE_MODEL_ID
    }

    fn dimensions(&self) -> usize {
        self.dimensions
    }

    fn embed(&self, text: &str) -> Result<Vec<f32>> {
        let acc = TokenSpaceAccumulator::global()?;
        Ok(acc.accumulate_text(text, self.dimensions))
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::semantic_embedder::SemanticEmbedder;

    #[test]
    fn embedded_matrix_loads() {
        let acc = TokenSpaceAccumulator::global().expect("load vocab");
        assert!(acc.token_count() > 100);
        assert_eq!(acc.dimensions(), VOCAB_NATIVE_DIMENSIONS);
    }

    #[test]
    fn known_tokens_stable_bits() {
        let emb = VocabAccumulateEmbedder::new(256).unwrap();
        let a = emb.embed_binary("checkout order cart process").unwrap();
        let b = emb.embed_binary("checkout order cart process").unwrap();
        assert_eq!(a, b);
        assert_eq!(a.len(), 32);
    }

    #[test]
    fn unknown_tokens_use_fnv_oov_fallback() {
        let acc = TokenSpaceAccumulator::global().unwrap();
        let mut tokens = HashSet::new();
        tokens.insert("zzzxqnotinvocab999".into());
        let a = acc.accumulate_tokens(&tokens);
        let b = acc.accumulate_tokens(&tokens);
        assert_eq!(a, b);
        assert!(a.iter().any(|&x| x != 0.0));
    }

    #[test]
    fn distill_round_trip_with_hash_teacher() {
        let tokens = parse_vocab_token_list("checkout\ncart\norder\n");
        let teacher = crate::semantic_embedder::SignHashEmbedder::new(64);
        let blob = distill_vocab_matrix(&teacher, &tokens, 64, 2).unwrap();
        let acc = TokenSpaceAccumulator::from_bytes(&blob).unwrap();
        assert_eq!(acc.token_count(), 3);
        assert_eq!(acc.dimensions(), 64);
        let query = acc.accumulate_text("checkout cart", 64);
        assert_eq!(query.len(), 64);
        assert!(query.iter().any(|&x| x != 0.0));
    }

    #[test]
    fn corrupt_matrix_rejected() {
        let err = TokenSpaceAccumulator::from_bytes(b"XXXX").unwrap_err();
        assert!(err.to_string().contains("magic") || err.to_string().contains("truncated"));
    }

    #[test]
    fn dim_packing_resize() {
        let emb = VocabAccumulateEmbedder::new(64).unwrap();
        let floats = emb.embed("checkout order").unwrap();
        assert_eq!(floats.len(), 64);
        assert_eq!(emb.embed_binary("checkout order").unwrap().len(), 8);
    }

    #[test]
    fn normalize_expands_endpoints_and_drops_filler() {
        let tokens = normalize_semantic_query_tokens("hey give me all my end points");
        assert!(tokens.contains("endpoint"));
        assert!(tokens.contains("endpoints"));
        assert!(tokens.contains("route"));
        assert!(!tokens.contains("hey"));
        assert!(!tokens.contains("give"));
        let keywords = canonicalize_query_keywords(tokens);
        assert_eq!(keywords, vec!["endpoint".to_string()]);
    }

    #[test]
    fn normalize_keeps_literal_class_when_only_filler_left() {
        let tokens = normalize_semantic_query_tokens("class");
        assert!(tokens.contains("class"));
    }
}
